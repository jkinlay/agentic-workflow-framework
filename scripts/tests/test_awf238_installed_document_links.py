"""Source docs must resolve within their installed projection, not the checkout."""
import json
from pathlib import Path, PurePosixPath
import posixpath
import re
import sys
import unittest
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / '.agentic/lib'))
from agentic import VERSION
from agentic.installer import managed


def installed_document_links(root, manifest):
    members = {path for path in manifest['files']
               if managed(path) or path.startswith('global/')}
    directories = {parent.as_posix() for path in members
                   for parent in PurePosixPath(path).parents}
    documents = sorted(path for path in members if path.endswith('.md'))
    generated = {('global/awf-portable/SKILL.md', target) for target in (
        f'assets/agentic-workflow-template-v{VERSION}.zip', 'assets/release.json')}
    targets = 0
    broken = []
    for document in documents:
        content = (root / document).read_text(encoding='utf-8')
        for line_number, line in enumerate(content.splitlines(), 1):
            # Match the installed self-test's Markdown target grammar.
            for target in re.findall(r'(?<!!)\[[^\]]+\]\(([^\s)]+)\)', line):
                target = unquote(target.strip('<>').split('#', 1)[0])
                if not target or re.match(r'[A-Za-z][A-Za-z0-9+.-]*:', target):
                    continue
                targets += 1
                resolved = posixpath.normpath(posixpath.join(
                    posixpath.dirname(document), target))
                # These two assets are generated by portable-skill packaging;
                # the installed self-test declares the same closed exception.
                if ((document, target) not in generated and
                        resolved not in members and resolved not in directories):
                    broken.append(f'{document}:{line_number} -> {target}')
    return {'documents': len(documents), 'relative_targets': targets, 'broken': broken}


class InstalledDocumentLinkTests(unittest.TestCase):
    def test_every_installed_document_and_skill_link_stays_in_installed_set(self):
        manifest = json.loads((ROOT / 'MANIFEST.json').read_bytes())
        result = installed_document_links(ROOT, manifest)
        self.assertGreater(result['documents'], 0)
        self.assertGreater(result['relative_targets'], 0)
        self.assertEqual([], result['broken'], '\n'.join(result['broken']))


if __name__ == '__main__':
    unittest.main()
